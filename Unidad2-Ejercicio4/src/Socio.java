public class Socio {

    private String nombre;
    private int numDeSocio;

    public Socio(String nombre, int numDeSocio) {
        this.nombre = nombre;
        this.numDeSocio = numDeSocio;
    }

    public String getNombre() {
        return nombre;
    }

    public int getNumDeSocio() {
        return numDeSocio;
    }
}